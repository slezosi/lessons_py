a = int(input("Введите значение первого катета прямоугольного треугольника: ")) #принимаем на вход значение двух переменных(первый катет и второй)
b = int(input("Введите значение второго катета прямоугольного треугольника: "))
S = a*b/2 #формула площади прямоугольного треугольника при наличии значения двух катетов, результат записывается в переменную S
print(f"Площадь прямоугольного треугольника с катетами {a} и {b} равна {S}") #вывод результата через команду print и f-строки
